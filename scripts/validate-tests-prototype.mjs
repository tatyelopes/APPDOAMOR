import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import vm from 'node:vm'
const context = vm.createContext({})
vm.runInContext(readFileSync(new URL('../docs/prototipo-testes-resultados.js', import.meta.url), 'utf8'), context)
const { create, catalog } = context.TestsPrototype
const start = (m, kind = 'affection') => { assert.ok(m.action('open', kind)); assert.ok(m.action('start')) }
const fill = (m, answers) => { for (const a of answers) { if (a === null) assert.ok(m.action('skip')); else { assert.ok(m.action('select', a)); assert.ok(m.action('next')) } } assert.equal(m.view().page, 'review') }
for (const kind of Object.keys(catalog)) {
 const m = create(); start(m, kind)
 assert.equal(m.action('next'), false); assert.equal(m.action('select', 6), false)
 m.action('select', 4); assert.equal(m.view().record.index, 0)
 m.action('pause'); m.action('catalog'); m.action('open', kind)
 assert.equal(m.view().page, 'paused'); m.action('resume'); assert.equal(m.view().record.answers[0], 4)
 fill(m, catalog[kind].items.map(() => 5)); assert.ok(m.action('finish'))
 assert.equal(m.view().record.result.highlights.length, catalog[kind].items.length)
 assert.equal(m.view().record.shared, false)
 m.setViewer(1); assert.equal(m.view().partner.length, 0)
 m.setViewer(0); m.action('open', kind); m.action('preview'); m.action('cancel')
 assert.equal(m.view().record.shared, false); m.action('preview'); assert.ok(m.action('share'))
 m.setViewer(1); assert.equal(m.view().partner.length, 1)
 assert.ok(!JSON.stringify(m.view().partner).includes('answers'))
 assert.ok(!JSON.stringify(m.view().partner).includes(catalog[kind].items[0][1]))
 m.setViewer(0); m.action('open', kind); m.setCondition('offline')
 assert.equal(m.action('revoke'), false); assert.equal(m.view().record.shared, true)
 m.setCondition('online'); assert.ok(m.action('revoke')); m.setViewer(1); assert.equal(m.view().partner.length, 0)
}
const partial = create(); start(partial); fill(partial, [5, null, 2, 5, null])
partial.action('edit', 2); partial.action('select', 1); partial.action('next')
assert.equal(partial.view().page, 'review'); assert.equal(partial.view().record.answers[2], 1)
partial.setCondition('fail'); assert.equal(partial.action('finish'), false)
assert.equal(partial.view().record.result, null); assert.equal(partial.view().page, 'review')
partial.setCondition('offline'); assert.equal(partial.action('finish'), false)
partial.setCondition('online'); assert.ok(partial.action('finish'))
assert.equal(partial.view().record.result.count, 3); assert.equal(partial.view().record.result.partial, true)
assert.equal(partial.view().record.result.highlights.length, 2); assert.equal(partial.action('finish'), false)
partial.action('preview'); partial.setCondition('fail'); assert.equal(partial.action('share'), false)
assert.equal(partial.view().record.shared, false); assert.ok(partial.action('share'))
partial.action('retake'); partial.action('cancel'); assert.equal(partial.view().record.shared, true)
partial.action('retake'); assert.ok(partial.action('confirm-retake'))
assert.equal(partial.view().record.result, null); assert.equal(partial.view().record.shared, false)
assert.ok(partial.view().record.answers.every(a => a === null))
const empty = create(); start(empty); fill(empty, [null, null, null, null, null])
assert.equal(empty.action('finish'), false); assert.equal(empty.view().record.result, null)
const low = create(); start(low); fill(low, [1, 2, 3, 2, 1]); low.action('finish')
assert.equal(low.view().record.result.highlights.length, 0)
low.action('preview'); low.action('share'); low.setCondition('expired')
assert.equal(low.view().page, 'expired'); assert.equal(low.view().record, undefined)
assert.equal(low.view().partner, undefined); assert.equal(low.action('catalog'), false)
low.setCondition('online'); low.setCondition('unlinked'); low.setCondition('online'); low.action('open', 'affection')
assert.ok(low.view().record.result); assert.equal(low.action('preview'), false)
low.setViewer(1); assert.equal(low.view().partner.length, 0)
console.log('OK: dois percursos, selecao, pausa, revisao, pulos, parcial, empates, falhas, privacidade, compartilhamento, revogacao, nova tentativa e acesso.')